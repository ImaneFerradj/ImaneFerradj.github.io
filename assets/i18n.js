  var LANGS = ["en", "fr", "ar", "ja"];
  var root = document.documentElement;

  function pick() {
    var l = null;
    try { l = new URLSearchParams(location.search).get("lang"); } catch (e) {}
    if (!l) { try { l = localStorage.getItem("lang"); } catch (e) {} }
    return LANGS.indexOf(l) > -1 ? l : "en";
  }

  function apply(l) {
    var d = D[l], en = D.en;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var k = el.getAttribute("data-i18n");
      var v = d[k] != null ? d[k] : en[k];
      if (v == null) return;
      if (el.tagName === "TITLE") document.title = v;
      else el.innerHTML = v;
    });
    document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
      var k = el.getAttribute("data-i18n-alt");
      var v = d[k] != null ? d[k] : en[k];
      if (v != null) el.setAttribute(el.tagName === "IMG" ? "alt" : "aria-label", v);
    });
    root.lang = l;
    root.dir = l === "ar" ? "rtl" : "ltr";
    document.querySelectorAll(".lang-switch select").forEach(function (s) { s.value = l; });
    root.classList.remove("i18n-pending");
  }

  function init() {
    apply(pick());
    document.querySelectorAll(".lang-switch select").forEach(function (s) {
      s.addEventListener("change", function () {
        try { localStorage.setItem("lang", s.value); } catch (e) {}
        try {
          var u = new URL(location.href);
          if (u.searchParams.has("lang")) { u.searchParams.set("lang", s.value); history.replaceState(null, "", u); }
        } catch (e) {}
        apply(s.value);
        if (window.umami && typeof window.umami.track === "function") {
          window.umami.track("language-change", { language: s.value });
        }
      });
    });
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
